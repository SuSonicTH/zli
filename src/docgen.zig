//! Build-time extraction of the Lua reference manual.
//!
//! The Lua 5.5 manual shipped with the `lua55` dependency is HTML.  This
//! module converts the language and standard-library parts of that manual to
//! a small Markdown dialect and emits a Lua module (`docs_manual.lua`) that is
//! attached to the ZLI payload.
//!
//! The C API (chapters 4 and 5, section 6.1) is deliberately not emitted.
//! Links to excluded sections are turned into plain text so the generated
//! manual has no dead C API references.

const std = @import("std");

const Managed = std.array_list.Managed;

pub const NodeKind = enum { heading, markdown, entry };

pub const Segment = struct {
    kind: enum { prose, heading },
    level: u8 = 0,
    inner: []const u8 = "",
};

pub const Heading = struct {
    level: u8,
    anchor: []const u8,
    title: []const u8,
    plain_title: []const u8,
    signature: []const u8,
    is_entry: bool,
};

pub const Entry = struct {
    name: []const u8,
    signature: []const u8,
    kind: []const u8,
    module: []const u8,
    anchor: []const u8,
    markdown: []const u8,
};

/// Extract the Lua release from lua.h (`LUA_VERSION_MAJOR_N` etc.).
pub fn versionFromHeader(allocator: std.mem.Allocator, header: []const u8) ![]u8 {
    const major = try macroValue(allocator, header, "LUA_VERSION_MAJOR_N");
    defer allocator.free(major);
    const minor = try macroValue(allocator, header, "LUA_VERSION_MINOR_N");
    defer allocator.free(minor);
    const release = try macroValue(allocator, header, "LUA_VERSION_RELEASE_N");
    defer allocator.free(release);
    return std.fmt.allocPrint(allocator, "{s}.{s}.{s}", .{ major, minor, release });
}

fn macroValue(allocator: std.mem.Allocator, header: []const u8, name: []const u8) ![]u8 {
    var lines = std.mem.splitScalar(u8, header, '\n');
    while (lines.next()) |line| {
        const trimmed = std.mem.trim(u8, line, " \t\r");
        if (!std.mem.startsWith(u8, trimmed, "#define ")) continue;
        var rest = trimmed["#define ".len..];
        rest = std.mem.trimStart(u8, rest, " \t");
        if (!std.mem.startsWith(u8, rest, name)) continue;
        var value = std.mem.trimStart(u8, rest[name.len..], " \t");
        while (value.len > 0 and (value[value.len - 1] == '\r' or value[value.len - 1] == ' ' or value[value.len - 1] == '\t')) {
            value = value[0 .. value.len - 1];
        }
        // Strip an integer suffix such as `u`/`L` if a platform adds one.
        while (value.len > 0 and (value[value.len - 1] == 'u' or value[value.len - 1] == 'U' or value[value.len - 1] == 'l' or value[value.len - 1] == 'L')) {
            value = value[0 .. value.len - 1];
        }
        return allocator.dupe(u8, value);
    }
    return error.MacroNotFound;
}

/// Generate the Lua source for `docs_manual.lua`.
pub fn generate(allocator: std.mem.Allocator, manual_html: []const u8, lua_header: []const u8) ![]u8 {
    var arena = std.heap.ArenaAllocator.init(allocator);
    defer arena.deinit();
    const a = arena.allocator();

    const version = try versionFromHeader(a, lua_header);
    const major_minor = if (std.mem.lastIndexOfScalar(u8, version, '.')) |dot| version[0..dot] else version;
    const segments = try parseSegments(a, manual_html);

    var out = Managed(u8).init(a);
    try out.appendSlice(
        \\-- Generated from the lua55 dependency's doc/manual.html.
        \\-- Do not edit by hand; this file is regenerated by the build.
        \\return {
        \\    meta = {
        \\
    );
    try out.appendSlice("        title = ");
    try appendLuaString(&out, try std.fmt.allocPrint(a, "Lua {s} Reference Manual", .{major_minor}));
    try out.appendSlice(",\n        version = ");
    try appendLuaString(&out, version);
    try out.appendSlice(
        \\,
        \\        source = "lua55",
        \\        license = "Lua license",
        \\        copyright = "Copyright (C) 1994-2026 Lua.org, PUC-Rio",
        \\        url = "https://www.lua.org/manual/5.5/",
        \\    },
        \\    nodes = {
        \\
    );

    var chapter: []const u8 = "";
    var section: []const u8 = "";
    var keep = false;
    var entry_count: usize = 0;
    var seen_1 = false;
    var seen_2 = false;
    var seen_3 = false;
    var seen_6 = false;
    var seen_9 = false;
    var i: usize = 0;
    while (i < segments.len) {
        const seg = segments[i];
        if (seg.kind == .prose) {
            if (keep) try emitMarkdown(&out, a, seg.inner);
            i += 1;
            continue;
        }

        const h = try parseHeading(a, seg.level, seg.inner);
        if (h.level == 1) {
            chapter = leadingNumber(h.plain_title);
            section = "";
            keep = isKeptChapter(chapter);
            if (std.mem.eql(u8, chapter, "1")) seen_1 = true;
            if (std.mem.eql(u8, chapter, "2")) seen_2 = true;
            if (std.mem.eql(u8, chapter, "3")) seen_3 = true;
            if (std.mem.eql(u8, chapter, "6")) seen_6 = true;
            if (std.mem.eql(u8, chapter, "9")) seen_9 = true;
        } else if (h.level == 2) {
            section = leadingNumber(h.plain_title);
            if (std.mem.eql(u8, chapter, "6") and std.mem.eql(u8, section, "6.1")) {
                keep = false;
            } else if (isKeptChapter(chapter)) {
                keep = true;
            }
        }

        if (!keep) {
            i += 1;
            continue;
        }

        if (h.is_entry) {
            entry_count += 1;
            var body = Managed(u8).init(a);
            var j = i + 1;
            while (j < segments.len and segments[j].kind == .prose) : (j += 1) {
                if (body.items.len > 0) try body.appendSlice("\n\n");
                const md = try htmlToMarkdown(a, segments[j].inner);
                try body.appendSlice(md);
            }
            const trimmed = std.mem.trim(u8, body.items, " \t\r\n");
            try emitEntry(&out, a, h, trimmed);
            i = j;
        } else {
            try emitHeading(&out, a, h);
            i += 1;
        }
    }

    if (manual_html.len > 10000 and (!seen_1 or !seen_2 or !seen_3 or !seen_6 or !seen_9 or entry_count < 100)) {
        const diagnostic = try manualFormatDiagnostic(a, seen_1, seen_2, seen_3, seen_6, seen_9, entry_count);
        std.log.err("{s}", .{diagnostic});
        return error.UnexpectedManualFormat;
    }

    try out.appendSlice(
        \\    },
        \\}
        \\
    );

    return allocator.dupe(u8, out.items);
}

fn parseSegments(arena: std.mem.Allocator, html: []const u8) ![]Segment {
    var segments = Managed(Segment).init(arena);

    const body_start = indexOfIgnoreCase(html, "<body") orelse 0;
    const body_tag_end = std.mem.indexOfScalarPos(u8, html, body_start, '>') orelse return segments.items;
    var pos = body_tag_end + 1;

    while (pos < html.len) {
        const hstart = findNextHeading(html, pos) orelse {
            if (pos < html.len) {
                try segments.append(.{ .kind = .prose, .inner = html[pos..] });
            }
            break;
        };
        if (hstart > pos) {
            try segments.append(.{ .kind = .prose, .inner = html[pos..hstart] });
        }

        const level = html[hstart + 2] - '0';
        const tag_end = std.mem.indexOfScalarPos(u8, html, hstart, '>') orelse break;
        const close = findClosingHeading(html, tag_end + 1, level) orelse break;
        try segments.append(.{
            .kind = .heading,
            .level = level,
            .inner = html[tag_end + 1 .. close.start],
        });
        pos = close.end;
    }

    return segments.items;
}

const CloseHeading = struct { start: usize, end: usize };

fn findClosingHeading(html: []const u8, start: usize, level: u8) ?CloseHeading {
    var i = start;
    while (i + 3 < html.len) : (i += 1) {
        if (html[i] != '<') continue;
        if (i + 1 >= html.len or html[i + 1] != '/') continue;
        if (i + 2 >= html.len) continue;
        if (std.ascii.toLower(html[i + 2]) != 'h') continue;
        if (html[i + 3] != '0' + level) continue;
        var j = i + 4;
        while (j < html.len and html[j] != '>') : (j += 1) {}
        if (j < html.len) return .{ .start = i, .end = j + 1 };
    }
    return null;
}

fn findNextHeading(html: []const u8, start: usize) ?usize {
    var i = start;
    while (i + 3 < html.len) : (i += 1) {
        if (html[i] != '<') continue;
        if (std.ascii.toLower(html[i + 1]) != 'h') continue;
        const c = html[i + 2];
        if (c < '1' or c > '4') continue;
        const after = html[i + 3];
        if (after != '>' and after != ' ' and after != '\t' and after != '\r' and after != '\n') continue;
        return i;
    }
    return null;
}

fn parseHeading(arena: std.mem.Allocator, level: u8, inner: []const u8) !Heading {
    const anchor = findAttribute(inner, "name") orelse "";
    const signature = extractCode(inner, arena) catch "";
    const title = try htmlToMarkdown(arena, inner);
    const plain = try htmlToPlainText(arena, inner);
    return .{
        .level = level,
        .anchor = anchor,
        .title = std.mem.trim(u8, title, " \t\r\n"),
        .plain_title = std.mem.trim(u8, plain, " \t\r\n"),
        .signature = std.mem.trim(u8, signature, " \t\r\n"),
        .is_entry = std.mem.startsWith(u8, anchor, "pdf-"),
    };
}

fn leadingNumber(text: []const u8) []const u8 {
    var i: usize = 0;
    while (i < text.len and text[i] >= '0' and text[i] <= '9') : (i += 1) {}
    if (i == 0) return "";
    var end = i;
    while (end < text.len and (text[end] == '.' or (text[end] >= '0' and text[end] <= '9'))) : (end += 1) {}
    // Do not consume the trailing dot in "6.2 – ...".
    while (end > 0 and text[end - 1] == '.') end -= 1;
    return text[0..end];
}

fn isKeptChapter(chapter: []const u8) bool {
    return std.mem.eql(u8, chapter, "1") or
        std.mem.eql(u8, chapter, "2") or
        std.mem.eql(u8, chapter, "3") or
        std.mem.eql(u8, chapter, "6") or
        std.mem.eql(u8, chapter, "9");
}

fn appendMissing(diagnostic: *Managed(u8), seen: bool, label: []const u8) !void {
    if (seen) return;
    if (diagnostic.items.len > 0) try diagnostic.appendSlice(", ");
    try diagnostic.appendSlice(label);
}

/// Explain which expected parts of the Lua manual were not found.  Build
/// failures used to carry only `error.UnexpectedManualFormat`, which made a
/// changed upstream manual layout hard to diagnose.
fn manualFormatDiagnostic(
    arena: std.mem.Allocator,
    seen_1: bool,
    seen_2: bool,
    seen_3: bool,
    seen_6: bool,
    seen_9: bool,
    entry_count: usize,
) ![]const u8 {
    var missing = Managed(u8).init(arena);
    try appendMissing(&missing, seen_1, "chapter 1");
    try appendMissing(&missing, seen_2, "chapter 2");
    try appendMissing(&missing, seen_3, "chapter 3");
    try appendMissing(&missing, seen_6, "chapter 6");
    try appendMissing(&missing, seen_9, "chapter 9");
    try appendMissing(&missing, entry_count >= 100, "at least 100 entries");
    return std.fmt.allocPrint(arena, "unexpected Lua manual format: found {d} entries; missing {s}", .{ entry_count, missing.items });
}

fn emitHeading(out: *Managed(u8), arena: std.mem.Allocator, h: Heading) !void {
    try out.appendSlice("        { type = \"heading\", level = ");
    const level = try std.fmt.allocPrint(arena, "{d}", .{h.level});
    try out.appendSlice(level);
    try out.appendSlice(", title = ");
    try appendLuaString(out, h.title);
    if (h.anchor.len > 0) {
        try out.appendSlice(", anchor = ");
        try appendLuaString(out, h.anchor);
    }
    try out.appendSlice(" },\n");
}

fn emitMarkdown(out: *Managed(u8), arena: std.mem.Allocator, html: []const u8) !void {
    const md = try htmlToMarkdown(arena, html);
    const trimmed = std.mem.trim(u8, md, " \t\r\n");
    if (trimmed.len == 0) return;
    try out.appendSlice("        { type = \"markdown\", text = ");
    try appendLuaString(out, trimmed);
    try out.appendSlice(" },\n");
}

fn emitEntry(out: *Managed(u8), arena: std.mem.Allocator, h: Heading, markdown: []const u8) !void {
    const name_and_kind = entryNameAndKind(h.signature);
    try out.appendSlice("        { type = \"entry\", name = ");
    try appendLuaString(out, name_and_kind.name);
    try out.appendSlice(", signature = ");
    try appendLuaString(out, h.signature);
    try out.appendSlice(", kind = ");
    try appendLuaString(out, name_and_kind.kind);
    try out.appendSlice(", module = ");
    try appendLuaString(out, entryModule(name_and_kind.name));
    try out.appendSlice(", anchor = ");
    try appendLuaString(out, h.anchor);
    try out.appendSlice(", markdown = ");
    try appendLuaString(out, markdown);
    try out.appendSlice(" },\n");
    _ = arena;
}

const NameAndKind = struct { name: []const u8, kind: []const u8 };

fn entryNameAndKind(signature: []const u8) NameAndKind {
    var end = signature.len;
    if (std.mem.indexOfScalar(u8, signature, '(')) |p| end = p;
    const name = std.mem.trim(u8, signature[0..end], " \t\r\n");
    const kind: []const u8 = if (std.mem.indexOfScalar(u8, name, ':') != null)
        "method"
    else if (std.mem.indexOfScalar(u8, signature, '(') != null)
        "function"
    else
        "field";
    return .{ .name = name, .kind = kind };
}

fn entryModule(name: []const u8) []const u8 {
    if (std.mem.startsWith(u8, name, "file:")) return "io";
    if (std.mem.indexOfScalar(u8, name, ':')) |p| return name[0..p];
    if (std.mem.indexOfScalar(u8, name, '.')) |p| return name[0..p];
    return "basic";
}

fn appendLuaString(out: *Managed(u8), value: []const u8) !void {
    // Pick a long-bracket delimiter that cannot occur in the value.
    var max_eq: usize = 0;
    var i: usize = 0;
    while (i < value.len) : (i += 1) {
        if (value[i] != ']') continue;
        var j = i + 1;
        while (j < value.len and value[j] == '=') : (j += 1) {}
        if (j < value.len and value[j] == ']') {
            const count = j - i - 1;
            if (count > max_eq) max_eq = count;
        }
    }
    const eqs = max_eq + 1;
    try out.append('[');
    var k: usize = 0;
    while (k < eqs) : (k += 1) try out.append('=');
    try out.append('[');
    try out.appendSlice(value);
    try out.append(']');
    var m: usize = 0;
    while (m < eqs) : (m += 1) try out.append('=');
    try out.append(']');
}

fn indexOfIgnoreCase(haystack: []const u8, needle: []const u8) ?usize {
    if (needle.len == 0) return 0;
    if (haystack.len < needle.len) return null;
    var i: usize = 0;
    while (i + needle.len <= haystack.len) : (i += 1) {
        var ok = true;
        for (needle, 0..) |c, k| {
            if (std.ascii.toLower(haystack[i + k]) != std.ascii.toLower(c)) {
                ok = false;
                break;
            }
        }
        if (ok) return i;
    }
    return null;
}

fn isAttributeNameChar(c: u8) bool {
    return std.ascii.isAlphanumeric(c) or c == '-' or c == '_' or c == ':' or c == '.';
}

fn findAttribute(html: []const u8, name: []const u8) ?[]const u8 {
    if (name.len == 0 or html.len < name.len) return null;

    var i: usize = 0;
    while (i + name.len <= html.len) : (i += 1) {
        // Avoid matching the tail of another attribute such as `data-name=`.
        if (i > 0 and isAttributeNameChar(html[i - 1])) continue;
        if (!std.ascii.eqlIgnoreCase(html[i .. i + name.len], name)) continue;

        var j = i + name.len;
        while (j < html.len and std.ascii.isWhitespace(html[j])) : (j += 1) {}
        if (j >= html.len or html[j] != '=') continue;
        j += 1;
        while (j < html.len and std.ascii.isWhitespace(html[j])) : (j += 1) {}
        if (j >= html.len) return null;

        const quote = html[j];
        if (quote == '"' or quote == '\'') {
            j += 1;
            const start = j;
            while (j < html.len and html[j] != quote) : (j += 1) {}
            return html[start..j];
        }

        // Tolerate unquoted attribute values as well.
        const start = j;
        while (j < html.len and !std.ascii.isWhitespace(html[j]) and html[j] != '>' and html[j] != '/') : (j += 1) {}
        return if (j > start) html[start..j] else null;
    }
    return null;
}

fn extractCode(html: []const u8, arena: std.mem.Allocator) ![]const u8 {
    const start = indexOfIgnoreCase(html, "<code") orelse return error.NotFound;
    const tag_end = std.mem.indexOfScalarPos(u8, html, start, '>') orelse return error.NotFound;
    const end = indexOfIgnoreCase(html[tag_end + 1 ..], "</code>") orelse return error.NotFound;
    return htmlToPlainText(arena, html[tag_end + 1 .. tag_end + 1 + end]);
}

fn appendCollapsed(out: *Managed(u8), text: []const u8, pending: *bool) !void {
    var i: usize = 0;
    while (i < text.len) {
        if (text[i] == '&') {
            const ent = decodeEntity(text[i..]) orelse {
                pending.* = false;
                try out.append('&');
                i += 1;
                continue;
            };
            if (pending.* and needsSpace(out.items)) try out.append(' ');
            pending.* = false;
            try out.appendSlice(ent.text);
            i += ent.len;
            continue;
        }
        const c = text[i];
        if (c == ' ' or c == '\t' or c == '\n' or c == '\r') {
            pending.* = true;
            i += 1;
            continue;
        }
        if (pending.* and needsSpace(out.items)) try out.append(' ');
        pending.* = false;
        switch (c) {
            '\\', '`', '*', '[', ']' => {
                try out.append('\\');
                try out.append(c);
            },
            else => try out.append(c),
        }
        i += 1;
    }
}

fn flushPending(out: *Managed(u8), pending: *bool) !void {
    if (pending.* and needsSpace(out.items)) try out.append(' ');
    pending.* = false;
}

fn needsSpace(out: []const u8) bool {
    if (out.len == 0) return false;
    const last = out[out.len - 1];
    return last != ' ' and last != '\n' and last != '\t' and last != '(' and last != '[' and last != '/';
}

const Entity = struct { text: []const u8, len: usize };

fn decodeEntity(text: []const u8) ?Entity {
    if (text.len < 3 or text[0] != '&') return null;
    const semi = std.mem.indexOfScalar(u8, text, ';') orelse return null;
    if (semi > 12) return null;
    const name = text[1..semi];
    const mapping = .{
        .{ "amp", "&" },
        .{ "lt", "<" },
        .{ "gt", ">" },
        .{ "quot", "\"" },
        .{ "apos", "'" },
        .{ "nbsp", " " },
        .{ "ndash", "–" },
        .{ "mdash", "—" },
        .{ "middot", "·" },
        .{ "sect", "§" },
        .{ "lsquo", "‘" },
        .{ "rsquo", "’" },
        .{ "ldquo", "“" },
        .{ "rdquo", "”" },
        .{ "le", "≤" },
        .{ "ge", "≥" },
        .{ "pi", "π" },
        .{ "copy", "©" },
        .{ "hellip", "…" },
    };
    inline for (mapping) |pair| {
        if (std.mem.eql(u8, name, pair[0])) return .{ .text = pair[1], .len = semi + 1 };
    }
    if (std.mem.startsWith(u8, name, "#")) {
        var digits = name[1..];
        var base: u8 = 10;
        if (digits.len > 0 and (digits[0] == 'x' or digits[0] == 'X')) {
            base = 16;
            digits = digits[1..];
        }
        if (digits.len == 0) return null;
        const value = std.fmt.parseInt(u21, digits, base) catch return null;
        var buf = [_]u8{ 0, 0, 0, 0 };
        const n = std.unicode.utf8Encode(value, &buf) catch return null;
        // Store a static buffer per entity: callers immediately append it.
        // This function is only used from appendCollapsed/htmlToPlainText and
        // the returned slice must remain valid until used. A thread-local
        // buffer is sufficient here.
        const Static = struct {
            threadlocal var buffer: [4]u8 = undefined;
        };
        @memcpy(Static.buffer[0..n], buf[0..n]);
        return .{ .text = Static.buffer[0..n], .len = semi + 1 };
    }
    return null;
}

fn htmlToPlainText(arena: std.mem.Allocator, html: []const u8) ![]const u8 {
    var out = Managed(u8).init(arena);
    var i: usize = 0;
    var pending_space = false;
    while (i < html.len) {
        if (html[i] == '<') {
            if (std.mem.startsWith(u8, html[i..], "<!--")) {
                const end = std.mem.indexOf(u8, html[i..], "-->") orelse break;
                i += end + 3;
                continue;
            }
            const end = std.mem.indexOfScalarPos(u8, html, i, '>') orelse break;
            i = end + 1;
            continue;
        }
        if (html[i] == '&') {
            if (decodeEntity(html[i..])) |ent| {
                if (pending_space and needsSpace(out.items)) try out.append(' ');
                pending_space = false;
                try out.appendSlice(ent.text);
                i += ent.len;
                continue;
            }
        }
        const c = html[i];
        if (c == ' ' or c == '\t' or c == '\n' or c == '\r') {
            pending_space = true;
        } else {
            if (pending_space and needsSpace(out.items)) try out.append(' ');
            pending_space = false;
            try out.append(c);
        }
        i += 1;
    }
    return out.items;
}

const LinkState = struct {
    href: []const u8,
    keep: bool,
    active: bool = false,
};

fn hrefIsExcluded(href: []const u8) bool {
    if (std.mem.eql(u8, href, "#4") or std.mem.startsWith(u8, href, "#4.")) return true;
    if (std.mem.eql(u8, href, "#5") or std.mem.startsWith(u8, href, "#5.")) return true;
    if (std.mem.startsWith(u8, href, "#6.1")) return true;
    if (std.mem.eql(u8, href, "#7") or std.mem.startsWith(u8, href, "#7.")) return true;
    if (std.mem.eql(u8, href, "#8") or std.mem.startsWith(u8, href, "#8.")) return true;
    if (std.mem.startsWith(u8, href, "#lua")) return true;
    if (std.mem.startsWith(u8, href, "#pdf-LUA_")) return true;
    return false;
}

fn normalizedHref(arena: std.mem.Allocator, href: []const u8) ![]const u8 {
    if (std.mem.startsWith(u8, href, "manual.html#")) {
        return std.fmt.allocPrint(arena, "#{s}", .{href["manual.html#".len..]});
    }
    if (std.mem.eql(u8, href, "manual.html") or
        std.mem.eql(u8, href, "contents.html") or
        std.mem.eql(u8, href, "readme.html") or
        std.mem.startsWith(u8, href, "contents.html#") or
        std.mem.startsWith(u8, href, "readme.html#"))
    {
        return "";
    }
    return href;
}

fn htmlToMarkdown(arena: std.mem.Allocator, html: []const u8) ![]const u8 {
    var out = Managed(u8).init(arena);
    var in_pre = false;
    var pre_first = false;
    var list_depth: usize = 0;
    var inline_code = false;
    var em_depth: usize = 0;
    var strong_depth: usize = 0;
    var pending_space = false;
    var link: ?LinkState = null;

    var i: usize = 0;
    while (i < html.len) {
        if (html[i] != '<') {
            const next = std.mem.indexOfScalarPos(u8, html, i, '<') orelse html.len;
            const text = html[i..next];
            if (in_pre) {
                var t = text;
                if (pre_first) {
                    pre_first = false;
                    if (std.mem.startsWith(u8, t, "\r\n")) {
                        t = t[2..];
                    } else if (std.mem.startsWith(u8, t, "\n")) {
                        t = t[1..];
                    }
                }
                try appendPreText(&out, t);
            } else if (inline_code) {
                try appendRawText(&out, text);
            } else {
                try appendCollapsed(&out, text, &pending_space);
            }
            i = next;
            continue;
        }

        if (std.mem.startsWith(u8, html[i..], "<!--")) {
            const end = std.mem.indexOf(u8, html[i..], "-->") orelse break;
            i += end + 3;
            continue;
        }

        const tag_end = std.mem.indexOfScalarPos(u8, html, i, '>') orelse break;
        const raw = html[i + 1 .. tag_end];
        const closing = raw.len > 0 and raw[0] == '/';
        var name_start: usize = if (closing) 1 else 0;
        while (name_start < raw.len and (raw[name_start] == ' ' or raw[name_start] == '\t')) : (name_start += 1) {}
        var name_end = name_start;
        while (name_end < raw.len and raw[name_end] != ' ' and raw[name_end] != '\t' and raw[name_end] != '\r' and raw[name_end] != '\n' and raw[name_end] != '/') : (name_end += 1) {}
        const name = raw[name_start..name_end];
        const self_closing = raw.len > 0 and raw[raw.len - 1] == '/';
        const tag = if (name.len > 0) std.ascii.toLower(name[0]) else 0;

        if (in_pre) {
            if (!closing and std.mem.eql(u8, name, "pre")) {
                // nested pre: ignore
            } else if (closing and std.mem.eql(u8, name, "pre")) {
                try ensureNewline(&out);
                try out.appendSlice("```\n\n");
                in_pre = false;
            }
            i = tag_end + 1;
            continue;
        }

        if (std.mem.eql(u8, name, "pre") and !closing) {
            pending_space = false;
            try ensureBlankLine(&out);
            // Only the current block matters when choosing a fence length.
            const block_start = tag_end + 1;
            const block_len = indexOfIgnoreCase(html[block_start..], "</pre>") orelse
                html.len - block_start;
            const fence = try fenceFor(arena, html[block_start .. block_start + block_len]);
            try out.appendSlice(fence);
            try out.append('\n');
            in_pre = true;
            pre_first = true;
            i = tag_end + 1;
            continue;
        }

        if (std.mem.eql(u8, name, "p")) {
            pending_space = false;
            if (closing) try ensureBlankLine(&out) else try ensureBlankLine(&out);
        } else if (std.mem.eql(u8, name, "b") or std.mem.eql(u8, name, "strong")) {
            // Emit only the outermost marker pair so nested HTML emphasis
            // becomes one valid Markdown span instead of `**a**b**`.
            if (!inline_code) {
                if (closing) {
                    if (strong_depth > 0) {
                        strong_depth -= 1;
                        if (strong_depth == 0) try out.appendSlice("**");
                    }
                } else {
                    strong_depth += 1;
                    if (strong_depth == 1) {
                        try flushPending(&out, &pending_space);
                        try out.appendSlice("**");
                    }
                }
            }
        } else if (std.mem.eql(u8, name, "em") or std.mem.eql(u8, name, "i")) {
            // As above for italic text.  Codes spans keep their literal text
            // even when they contain presentational tags.
            if (!inline_code) {
                if (closing) {
                    if (em_depth > 0) {
                        em_depth -= 1;
                        if (em_depth == 0) try out.append('*');
                    }
                } else {
                    em_depth += 1;
                    if (em_depth == 1) {
                        try flushPending(&out, &pending_space);
                        try out.append('*');
                    }
                }
            }
        } else if (std.mem.eql(u8, name, "code")) {
            if (!inline_code) {
                try flushPending(&out, &pending_space);
                try out.append('`');
                inline_code = true;
            } else {
                try out.append('`');
                inline_code = false;
            }
        } else if (std.mem.eql(u8, name, "a")) {
            if (!closing) {
                if (findAttribute(raw, "href")) |href| {
                    const norm = try normalizedHref(arena, href);
                    if (norm.len == 0 or hrefIsExcluded(norm)) {
                        link = .{ .href = norm, .keep = false };
                    } else {
                        try flushPending(&out, &pending_space);
                        try out.append('[');
                        link = .{ .href = norm, .keep = true, .active = true };
                    }
                } else {
                    link = .{ .href = "", .keep = false };
                }
            } else {
                if (link) |state| {
                    if (state.keep) {
                        try out.appendSlice("](");
                        try out.appendSlice(state.href);
                        try out.append(')');
                    }
                    link = null;
                }
            }
        } else if (std.mem.eql(u8, name, "ul") or std.mem.eql(u8, name, "ol")) {
            pending_space = false;
            if (!closing) {
                if (list_depth == 0) try ensureBlankLine(&out);
                list_depth += 1;
            } else {
                if (list_depth > 0) list_depth -= 1;
                try ensureNewline(&out);
                if (list_depth == 0) try ensureBlankLine(&out);
            }
        } else if (std.mem.eql(u8, name, "li")) {
            pending_space = false;
            if (!closing) {
                try ensureNewline(&out);
                var d = if (list_depth > 0) list_depth - 1 else 0;
                while (d > 0) : (d -= 1) try out.appendSlice("  ");
                try out.appendSlice("- ");
            } else {
                try ensureNewline(&out);
            }
        } else if (std.mem.eql(u8, name, "sup")) {
            if (!closing) {
                try flushPending(&out, &pending_space);
                try out.append('^');
            }
        } else if (std.mem.eql(u8, name, "sub")) {
            if (!closing) {
                try flushPending(&out, &pending_space);
                try out.append('~');
            }
        } else if (std.mem.eql(u8, name, "br")) {
            try ensureNewline(&out);
        } else if (std.mem.eql(u8, name, "hr")) {
            // Separators before entries are redundant; the entry heading is
            // enough. Other rules are not used by the manual body.
        }

        _ = tag;
        _ = self_closing;
        i = tag_end + 1;
    }

    if (in_pre) try out.appendSlice("\n```\n");
    return out.items;
}

fn appendRawText(out: *Managed(u8), text: []const u8) !void {
    var i: usize = 0;
    while (i < text.len) {
        if (text[i] == '&') {
            if (decodeEntity(text[i..])) |ent| {
                try out.appendSlice(ent.text);
                i += ent.len;
                continue;
            }
        }
        try out.append(text[i]);
        i += 1;
    }
}

fn appendPreText(out: *Managed(u8), text: []const u8) !void {
    var i: usize = 0;
    while (i < text.len) {
        if (text[i] == '&') {
            if (decodeEntity(text[i..])) |ent| {
                try out.appendSlice(ent.text);
                i += ent.len;
                continue;
            }
        }
        try out.append(text[i]);
        i += 1;
    }
}

fn fenceFor(arena: std.mem.Allocator, block: []const u8) ![]const u8 {
    var count: usize = 3;
    var run: usize = 0;
    for (block) |c| {
        if (c == '`') {
            run += 1;
            if (run >= count) count = run + 1;
        } else {
            run = 0;
        }
    }
    const fence = try arena.alloc(u8, count);
    @memset(fence, '`');
    return fence;
}

fn ensureNewline(out: *Managed(u8)) !void {
    if (out.items.len == 0) return;
    if (out.items[out.items.len - 1] != '\n') try out.append('\n');
}

fn ensureBlankLine(out: *Managed(u8)) !void {
    if (out.items.len == 0) return;
    try ensureNewline(out);
    if (out.items.len < 2 or out.items[out.items.len - 2] != '\n') try out.append('\n');
}

