test "nested emphasis and inline code" {
    var arena = std.heap.ArenaAllocator.init(std.testing.allocator);
    defer arena.deinit();
    const a = arena.allocator();

    const md = try htmlToMarkdown(a,
        \\<p><b><em>x</em></b></p>
        \\<p><em>outer <em>n</em> end</em></p>
        \\<p><code>\x<em>XX</em></code></p>
    );

    // Nested bold/italic stays one combined span.
    try std.testing.expect(std.mem.indexOf(u8, md, "***x***") != null);
    // Nested same-kind emphasis collapses to one balanced pair.
    try std.testing.expect(std.mem.indexOf(u8, md, "*outer n end*") != null);
    try std.testing.expect(std.mem.indexOf(u8, md, "**outer") == null);
    // Presentational tags inside inline code are ignored.
    try std.testing.expect(std.mem.indexOf(u8, md, "`\\xXX`") != null);
    try std.testing.expect(std.mem.indexOf(u8, md, "*XX*") == null);
}

